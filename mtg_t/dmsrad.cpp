//////////////////////////////////////////////////////////////////////////
//  将度分秒连写的(double型)角度化为弧度值
double dms2rad(double a)
{
	//提取角度值的符号
	double sign=(a<0.0) ? -1.0 : 1.0;
	a=fabs(a);

	//提取角度值的整度
	int d=(int)(a+0.00001);
	a=a-d;
	if(a<0.0){ d=d-1; a=a+1;}

	//提取角度值的整分及秒值
	int m=(int)((a+0.00001)*100.0);
	a=a-m/100.0;
	if(a<0.0){ m=m-1; a=a+0.01;}

	a=a*10000.0;

	a=sign*(d*3600.0+m*60.0+a)/206264.806247096363;

	return a;
}

//////////////////////////////////////////////////////////////////////////
//  将度分秒连写的(double型)角度化为弧度值
double dms2deg(double a)
{
    //提取角度值的符号
	double sign=(a<0.0) ? -1.0 : 1.0;
	a=fabs(a);
	//提取角度值的整度
	int d=a;
	//提取角度值的整分及秒值
	int m=(a-d)*100;
	double s=a-(d+m/100.0);
	s=s*10000.0;
    a=d+m/60.0+s/3600.0;
	a=a*sign;
	return a;
}

//////////////////////////////////////////////////////////////////////////
//  将角度的弧度值化为度分秒连写的角度（double 型）dd.mmss
double rad2dms(double a)
{
	a=a*206264.806247096363;

	double sign=(a<0.0) ? -1.0 : 1.0;
	a=fabs(a);

	int d=(int)(a/3600.0+0.0000001);
	a=a-d*3600.0;

	if(a<0.0){ d=d-1; a=a+3600.0; }

	int m=(int)(a/60.0+0.0001);
	a=a-m*60.0;
	if(a<0.0){ m=m-1; a=a+60.0; }

	//a=d*10000.0+m*100.0+a;
	a=d+m/100.0+a/10000.0;

	return a*sign;
}
